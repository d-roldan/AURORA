async (page)=>{
 const checks=[];const check=(ok,label)=>{if(!ok)throw new Error(label);checks.push(label);};
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:1440,height:1100});
 await page.goto('http://localhost:8085/crew');
 await page.locator('.profile').first().waitFor();
 const portraits=page.locator('.profile .crew-portrait img');
 await portraits.first().waitFor();
 await page.waitForFunction(()=>[...document.querySelectorAll('.profile .crew-portrait img')].length===4&&[...document.querySelectorAll('.profile .crew-portrait img')].every(img=>img.complete&&img.naturalWidth>0));
 check(await portraits.count()===4,'All four roster profiles display loaded photographic portraits');
 const sourceById=await page.locator('.profile .crew-portrait').evaluateAll(nodes=>Object.fromEntries(nodes.map(node=>[node.dataset.crewId,node.querySelector('img').getAttribute('src')])));
 check(new Set(Object.values(sourceById)).size===4,'Each stable crew identity has a distinct portrait');
 const sidebar=page.locator('aside.sidebar');
 if(await sidebar.getAttribute('data-collapsed')==='true')await page.locator('.sidebar-toggle').click();
 check(await sidebar.evaluate(el=>el.getBoundingClientRect().width)>180,'Desktop sidebar expands with labels');
 await page.locator('.sidebar-toggle').focus();await page.keyboard.press('Enter');
 check(await sidebar.getAttribute('data-collapsed')==='true','Keyboard toggles sidebar to collapsed');
 check(await page.locator('main').evaluate(el=>el.getBoundingClientRect().left)===64,'Content uses released space in collapsed layout');
 check(await sidebar.locator('nav a').count()===7,'All navigation links remain available when collapsed');
 check(await sidebar.locator('nav a').evaluateAll(links=>links.every(link=>!!link.getAttribute('aria-label')&&!!link.title)),'Collapsed links keep accessible names and hover labels');
 await page.reload();await page.locator('.profile').first().waitFor();
 check(await sidebar.getAttribute('data-collapsed')==='true','Collapsed preference survives reload');
 await page.locator('.sidebar-toggle').click();
 await page.screenshot({path:'output/playwright/crew-portraits-expanded.png',fullPage:true});
 await page.locator('a.profile').first().click();
 await page.locator('.personal-header .crew-portrait img').waitFor();
 const id=await page.locator('.personal-header .crew-portrait').getAttribute('data-crew-id');
 check(await page.locator('.personal-header .crew-portrait img').getAttribute('src')===sourceById[id],'Profile header retains the same identity portrait');
 await page.locator('.sidebar-toggle').click();
 await page.screenshot({path:'output/playwright/crew-profile-collapsed.png',fullPage:true});
 // Only the browser loses one portrait; no data or services change.
 const block=route=>route.abort('failed');await page.route('**/images/crew/crew-01.png',block);
 await page.goto('http://localhost:8085/crew');
 await page.locator('.profile .crew-portrait-fallback').waitFor();
 check(await page.locator('.profile .crew-portrait-fallback').count()===1,'Unavailable portrait falls back to identified initials without substituting another person');
 check(await page.locator('.profile').first().locator('h2').textContent()==='Lucas Orozco','Image failure preserves the astronaut name');
 await page.unroute('**/images/crew/crew-01.png',block);await page.reload();
 await page.waitForFunction(()=>[...document.querySelectorAll('.profile .crew-portrait img')].length===4&&[...document.querySelectorAll('.profile .crew-portrait img')].every(img=>img.complete&&img.naturalWidth>0));
 await page.setViewportSize({width:390,height:844});
 if(await sidebar.getAttribute('data-collapsed')==='true')await page.locator('.sidebar-toggle').click();
 check(await sidebar.evaluate(el=>el.getBoundingClientRect().width)===224,'Mobile navigation can expand from the compact rail');
 check(await page.locator('.sidebar-backdrop').isVisible(),'Mobile expansion provides an outside close control');
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Expanded mobile menu does not cause horizontal overflow');
 await page.screenshot({path:'output/playwright/sidebar-mobile-expanded.png',fullPage:true});
 await sidebar.locator('a[href="/settings"]').click();
 check(await sidebar.getAttribute('data-collapsed')==='true','Choosing a mobile destination closes the expanded menu');
 check(await page.locator('.settings-grid').isVisible(),'Settings remain accessible with the compact sidebar');
 await page.getByRole('radio',{name:'ES Español',exact:true}).click();
 await page.getByRole('radio',{name:/Modo oscuro/}).click();
 check(await page.getByRole('button',{name:'Desplegar barra lateral',exact:true}).count()===1,'Toggle is translated into Spanish');
 await page.getByRole('button',{name:'Desplegar barra lateral',exact:true}).click();
 await sidebar.getByRole('link',{name:'Tripulación',exact:true}).click();
 await page.locator('.profile .crew-portrait img').first().waitFor();
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Portrait roster fits mobile width in the dark theme');
 await page.screenshot({path:'output/playwright/crew-mobile-es-dark.png',fullPage:true});
 check(errors.length===0,'No browser JavaScript exceptions');
 return {passed:true,checks};
}

